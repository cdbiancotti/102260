# Dict

## Conjunto diccionario
# diccionario = {}
# print("Diccionario:", diccionario)
# print("La diccionario es del tipo:", type(diccionario))

## Formato Clave-Valor

# Los datos guardados en un diccionario usan el formato clave/llave/key - valor/value
# Donde la clave/llave/key solo puede ser un valor inmutable
# Donde el alor/value puede ser cualquier tipo de dato

# diccionario = {llave1: valor1, llave2: valor2, llave3: valor3, etc...}

# diccionario = {
#     llave1: valor1,
#     llave2: valor2,
#     llave3: valor3,
#     etc...
# }

diccionario = {
    1: 'Hola Don Pepito',
    False: [1,2,3,4,5],
    ('valor', 5.5): {
        'llave1': 'valor1'
    } 
}
print("Diccionario:", diccionario)

## Acceso a datos

print('Elemento de clave 1:', diccionario[1])
print("Elemento de clave ('valor', 5.5):", diccionario[('valor', 5.5)])

## Mutable

# Agregar
diccionario['llave nueva'] = 'valor nuevo'
print("Diccionario:", diccionario)

# Modificar
diccionario['llave nueva'] = 123
print("Diccionario:", diccionario)

# "Eliminar" (extraer)
dato_extraido = diccionario.pop('asd', 'La llave usada no existe')
print("Diccionario:", diccionario)
print("Dato extraido:", dato_extraido)

